export type MessageKey = keyof typeof english;
export type MessageValues = Record<string, string | number>;
export function translate(locale: Locale, key: MessageKey, values: MessageValues = {}): string {
  const template = locale === "en" ? english[key] : key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => Object.hasOwn(values, name) ? String(values[name]) : match);
}

export function localizeError(locale: Locale, message: string): string {
  if (!message) return "";
  // API error text stays language-neutral in state, so existing errors translate without refetching.
  return translate(locale, Object.hasOwn(english, message) ? message as MessageKey : "请检查网络连接，稍后重试。");
}

const displayNames = new Map<Locale, Intl.DisplayNames>();
export function localizedCurrencyName(code: string, locale: Locale, currency?: Pick<Currency, "name" | "englishName">): string {
  if (locale === "zh-CN") return currency?.name || currencyName(code);
  try {
    let names = displayNames.get(locale);
    if (!names) { names = new Intl.DisplayNames([locale], { type: "currency" }); displayNames.set(locale, names); }
    return names.of(code) || currency?.englishName || code;
  } catch { return currency?.englishName || code; }
}

export function localizedSource(source: string, locale: Locale): string {
  if (locale !== "en") return source;
  if (source === "Open Exchange Rates · 小时参考汇率") return "Open Exchange Rates · Hourly reference rates";
  if (source === "Frankfurter · 央行综合参考汇率") return "Frankfurter · Central bank reference rates";
  return source;
}
